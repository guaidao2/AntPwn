#!/bin/bash
# Real gdb plugin smoke test: drives an actual inferior, so offset/trace/
# prompt/completion/leak paths are exercised instead of only importing code.
# Usage: bash tests/gdb_smoke.sh   (needs gdb + a build of challenges/bin/baby_bof)
set -u
cd "$(dirname "$0")/.." || exit 1
ROOT="$(pwd)"
BIN="$ROOT/challenges/bin/baby_bof"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
FAILED=0

check() {  # name, file, pattern
    if grep -qE "$3" "$2"; then
        echo "ok   - $1"
    else
        echo "FAIL - $1 (missing: $3)"
        FAILED=1
    fi
}

if ! command -v gdb >/dev/null 2>&1; then
    echo "gdb not installed, skipping gdb smoke"
    exit 0
fi
if [ ! -x "$BIN" ]; then
    echo "missing $BIN, skipping gdb smoke"
    exit 0
fi

# a pwnlib-compatible pattern, generated by AntPwn itself
python3 - "$TMP/pattern.bin" <<'PY'
import sys
from antpwn.exploits import cyclic
open(sys.argv[1], "wb").write(cyclic(512) + b"\n")
PY

echo "== gdb: analysis commands =="
gdb -q -batch \
    -ex "source antpwn-gdb.py" \
    -ex "file $BIN" \
    -ex "break main" \
    -ex "run" \
    -ex "antpwn where" \
    -ex "antpwn disas" \
    -ex "antpwn pseudo" \
    -ex "antpwn x \$rsp 32" \
    -ex "antpwn leak \$rsp" \
    -ex "antpwn maps" \
    -ex "antpwn vuln --bp" \
    -ex "antpwn plan" \
    > "$TMP/analysis.log" 2>&1
check 'where shows $pc' "$TMP/analysis.log" "== where =="
check 'disas defaults to $pc' "$TMP/analysis.log" "=>"
check 'x reads stack' "$TMP/analysis.log" "== x \\\$rsp"
check 'leak resolves a mapping' "$TMP/analysis.log" "== leak =="
check 'maps lists regions' "$TMP/analysis.log" "== mappings =="
check 'vuln suggests breakpoints' "$TMP/analysis.log" "b \\*0x"
check 'plan lists next steps' "$TMP/analysis.log" "priority="

echo "== gdb: offset + cvar + reset =="
gdb -q -batch \
    -ex "source antpwn-gdb.py" \
    -ex "file $BIN" \
    -ex "run < $TMP/pattern.bin" \
    -ex "antpwn offset" \
    -ex "python print('CVAR_OFFSET', int(gdb.parse_and_eval('\$antpwn_offset')))" \
    -ex "antpwn reset" \
    -ex "python print('CVAR_RESET', int(gdb.parse_and_eval('\$antpwn_offset')))" \
    > "$TMP/offset.log" 2>&1
check "offset decoded from crash" "$TMP/offset.log" "offset=72"
check "convenience variable set" "$TMP/offset.log" "CVAR_OFFSET 72"
check "reset zeroes the variable" "$TMP/offset.log" "CVAR_RESET 0"

echo "== gdb: trace + prompt chain + completion =="
gdb -q -batch \
    -ex "python gdb.prompt_hook = lambda p: 'PREV> '" \
    -ex "source antpwn-gdb.py" \
    -ex "file $BIN" \
    -ex "antpwn trace on gets --stop --dump --max=2" \
    -ex "run < $TMP/pattern.bin" \
    -ex "antpwn trace show" \
    -ex "python import antpwn.gdbplugin as gp; print('PROMPT_ON', repr(gp._prompt_hook('(gdb) ')))" \
    -ex "antpwn prompt off" \
    -ex "python import antpwn.gdbplugin as gp; print('PROMPT_OFF', repr(gp._prompt_hook('(gdb) ')))" \
    -ex "complete antpwn tr" \
    > "$TMP/trace.log" 2>&1
check "trace hits gets" "$TMP/trace.log" "\[trace\] gets"
check "trace computes saved_rip" "$TMP/trace.log" "saved_rip≈"
check "prompt enabled" "$TMP/trace.log" "PROMPT_ON '\\\\x01"
check "prompt restores previous hook" "$TMP/trace.log" "PROMPT_OFF 'PREV> '"
check "tab completion works" "$TMP/trace.log" "antpwn trace"

echo "== gdb: session export / report =="
gdb -q -batch \
    -ex "source antpwn-gdb.py" \
    -ex "file $BIN" \
    -ex "run < $TMP/pattern.bin" \
    -ex "antpwn offset" \
    -ex "antpwn export $TMP/session.json" \
    -ex "antpwn report $TMP/session.html" \
    > "$TMP/export.log" 2>&1
check "json export saved" "$TMP/export.log" "session.json"
check "html report saved" "$TMP/export.log" "session.html"
python3 - "$TMP/session.json" "$TMP/session.html" <<'PY'
import json, sys
d = json.load(open(sys.argv[1]))
s = d.get("session") or {}
assert s.get("offset") == 72, s.get("offset")
assert "gdb" in s
assert len(open(sys.argv[2]).read()) > 500
print("ok   - session payload + HTML content")
PY
[ $? -eq 0 ] || FAILED=1

if [ "$FAILED" -ne 0 ]; then
    echo "GDB SMOKE FAILED"
    exit 1
fi
echo "GDB SMOKE OK"
